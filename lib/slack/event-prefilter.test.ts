import { beforeEach, describe, expect, it, vi } from "vitest";
import {
  getSlackEventMetricsSnapshot,
  resetSlackEventMetrics,
} from "@/lib/slack/event-metrics";
import {
  prefilterSlackMessageEvent,
  type SlackEventCallbackPayload,
  type SlackPrefilterSupabaseClient,
  type SlackSkipReason,
} from "@/lib/slack/event-prefilter";

type FakeWorkspace = {
  id: string;
  slack_bot_user_id: string | null;
};

type FakeChannel = {
  id: string;
  is_tracked: boolean;
};

type FakeContact = {
  id: string;
  is_active: boolean;
};

type FakeSupabaseRows = {
  workspace?: FakeWorkspace | null;
  channel?: FakeChannel | null;
  contact?: FakeContact | null;
};

const basePayload: SlackEventCallbackPayload = {
  type: "event_callback",
  team_id: "T123",
  event_id: "Ev123",
  event: {
    type: "message",
    channel: "C123",
    user: "U123",
    ts: "1710000000.000100",
    text: "Can we expand the deliverables for launch next week?",
  },
};

function payload(
  overrides: Partial<SlackEventCallbackPayload> = {},
): SlackEventCallbackPayload {
  return {
    ...basePayload,
    ...overrides,
    event: Object.hasOwn(overrides, "event")
      ? overrides.event
      : { ...basePayload.event },
  };
}

function createFakeSupabase(
  rows: FakeSupabaseRows = {},
): SlackPrefilterSupabaseClient {
  const defaults: Required<FakeSupabaseRows> = {
    workspace: { id: "workspace-1", slack_bot_user_id: "UBOT" },
    channel: { id: "channel-1", is_tracked: true },
    contact: { id: "contact-1", is_active: true },
  };
  const resolved = { ...defaults, ...rows };

  return {
    from(table: string) {
      return {
        select() {
          return this;
        },
        eq() {
          return this;
        },
        async maybeSingle() {
          if (table === "workspaces") {
            return { data: resolved.workspace, error: null };
          }
          if (table === "channels") {
            return { data: resolved.channel, error: null };
          }
          if (table === "client_contacts") {
            return { data: resolved.contact, error: null };
          }

          return {
            data: null,
            error: { message: `Unexpected table ${table}` },
          };
        },
      };
    },
  } as unknown as SlackPrefilterSupabaseClient;
}

async function expectSkipped(
  slackPayload: SlackEventCallbackPayload,
  reason: SlackSkipReason,
  rows?: FakeSupabaseRows,
) {
  const result = await prefilterSlackMessageEvent(
    slackPayload,
    createFakeSupabase(rows),
  );

  expect(result).toMatchObject({ accepted: false, reason });
  expect(getSlackEventMetricsSnapshot().skipped[reason]).toBe(1);
}

beforeEach(() => {
  resetSlackEventMetrics();
  vi.spyOn(console, "info").mockImplementation(() => undefined);
});

describe("prefilterSlackMessageEvent", () => {
  it("skips payloads without an event", async () => {
    await expectSkipped(payload({ event: undefined }), "missing_event");
  });

  it("skips unsupported event types", async () => {
    await expectSkipped(
      payload({ event: { ...basePayload.event, type: "reaction_added" } }),
      "unsupported_event_type",
    );
  });

  it("skips bot message subtypes", async () => {
    await expectSkipped(
      payload({ event: { ...basePayload.event, subtype: "bot_message" } }),
      "bot_message_subtype",
    );
  });

  it("skips app-generated messages", async () => {
    await expectSkipped(
      payload({ event: { ...basePayload.event, app_id: "A123" } }),
      "app_generated_message",
    );
  });

  it("skips messages generated by the connected bot user", async () => {
    await expectSkipped(
      payload({ event: { ...basePayload.event, user: "UBOT" } }),
      "app_generated_message",
    );
  });

  it("skips events without a Slack team", async () => {
    await expectSkipped(payload({ team_id: undefined }), "missing_team");
  });

  it("skips events for unconnected workspaces", async () => {
    await expectSkipped(payload(), "workspace_not_connected", {
      workspace: null,
    });
  });

  it("skips events without a channel", async () => {
    await expectSkipped(
      payload({ event: { ...basePayload.event, channel: undefined } }),
      "missing_channel",
    );
  });

  it("skips events from untracked channels", async () => {
    await expectSkipped(payload(), "untracked_channel", {
      channel: { id: "channel-1", is_tracked: false },
    });
  });

  it("skips events without a user", async () => {
    await expectSkipped(
      payload({ event: { ...basePayload.event, user: undefined } }),
      "missing_user",
    );
  });

  it("skips events from users who are not client contacts", async () => {
    await expectSkipped(payload(), "unknown_client_contact", { contact: null });
  });

  it("skips events from inactive client contacts", async () => {
    await expectSkipped(payload(), "inactive_client_contact", {
      contact: { id: "contact-1", is_active: false },
    });
  });

  it("skips low-signal acknowledgement messages", async () => {
    await expectSkipped(
      payload({ event: { ...basePayload.event, text: "Sounds good!" } }),
      "low_signal_message",
    );
  });

  it("skips messages shorter than five words", async () => {
    await expectSkipped(
      payload({
        event: { ...basePayload.event, text: "Add reporting please" },
      }),
      "message_too_short",
    );
  });

  it("accepts client messages from tracked channels", async () => {
    const result = await prefilterSlackMessageEvent(
      payload(),
      createFakeSupabase(),
    );

    expect(result).toEqual({
      accepted: true,
      eventId: "Ev123",
      workspaceId: "workspace-1",
      channelId: "channel-1",
      clientContactId: "contact-1",
    });
    expect(getSlackEventMetricsSnapshot()).toEqual({
      received: 0,
      accepted: 1,
      skipped: {},
    });
  });
});
